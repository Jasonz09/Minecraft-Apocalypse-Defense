/**
 * @param {any} record
 * @returns {Map<string, () => any[]>}
 */
function liveOrThrow(record) {
    const lazy = record !== null && typeof record === "object" ? LAZY_OPS.get(record) : undefined;
    if (lazy === undefined) {
        throw new Error("this site record has no live op generators (it was cloned, parsed from JSON or restored after a restart): call rehydrateSite(plan, index, groundJSON, options) and use the record it returns");
    }
    return lazy;
}

/**
 * Ops of one element, regenerated from its descriptor. Deterministic and side-effect free. Throws
 * on a record without live generators.
 *
 * @param {any} record
 * @param {string} stage
 * @param {number} elementIndex
 * @returns {any[]}
 */
export function siteOpsFor(record, stage, elementIndex) {
    const lazy = liveOrThrow(record);
    const list = /** @type {any[]} */ (record?.[stage] ?? []);
    const element = list[elementIndex];
    if (element === undefined) {
        throw new RangeError(`no element ${String(stage)}[${String(elementIndex)}]`);
    }
    const producer = lazy.get(`${stage}:${element.id}`);
    if (producer === undefined) {
        throw new Error(`site record has no generator for ${stage}/${String(element.id)}`);
    }
    return producer();
}

/**
 * @param {any} record
 * @param {string} stage
 * @param {string} elementId
 */
export function siteOpsById(record, stage, elementId) {
    liveOrThrow(record);
    const list = /** @type {any[]} */ (record?.[stage] ?? []);
    const at = list.findIndex((element) => element.id === elementId);
    if (at < 0) {
        throw new RangeError(`no element ${String(stage)}/${String(elementId)}`);
    }
    return siteOpsFor(record, stage, at);
}

/**
 * Bounded slices across every stage, in job order. Holds one slice at a time. Throws on a record
 * without live generators.
 *
 * @param {any} record
 * @param {{ maxOps?: number, stages?: string[] }} [options]
 */
export function* siteOpSlices(record, options = {}) {
    liveOrThrow(record);
    const limit = Math.min(Number(options.maxOps ?? CIV_LIMITS.maxBlocksPerSlice), CIV_LIMITS.maxBlocksPerSlice);
    const stages = /** @type {string[]} */ (options.stages ?? STAGES);
    for (const stage of stages) {
        const list = /** @type {any[]} */ (record?.[stage] ?? []);
        for (let index = 0; index < list.length; index += 1) {
            const ops = siteOpsFor(record, stage, index);
            for (let start = 0; start < ops.length; start += limit) {
                yield { stage, element: list[index].id, elementIndex: index, ops: ops.slice(start, start + limit) };
            }
        }
    }
}

/**
 * Element specs for `civ/jobs.js` createQueue: exact totals plus an op-content hash.
 * @param {any} record
 */
export function siteJobSpecs(record) {
    /** @type {Record<string, any[]>} */
    const specs = {};
    for (const stage of STAGES) {
        specs[stage] = /** @type {any[]} */ (record?.[stage] ?? []).map((element) => ({
            total: element.total,
            hash: Number.parseInt(String(element.hash), 16),
            inputs: { id: element.id, kind: element.kind, bbox: element.bbox },
        }));
    }
    return specs;
}

/**
 * Structures must sit inside their own district. Walls, gates, gate bands and wall stairs are
 * boundary structures and are exempt. Streets and arterials must be wholly inside. A link road
 * is an approved connection: it may leave, but only toward one paired district and only through
 * a gate it actually passes by.
 *
 * @param {any} plan
 * @param {number} index
 * @param {any} record
 * @returns {string[]}
 */
export function siteContainmentProblems(plan, index, record) {
    return runSync(siteContainmentProblemsSteps(plan, index, record, newOps()));
}

/**
 * Cooperative form of siteContainmentProblems (one implementation): regenerates one element at a time and
 * yields between elements.
 *
 * @param {any} plan
 * @param {number} index
 * @param {any} record
 * @param {Ops} [ops]
 * @returns {Generator<void, string[], void>}
 */
export function* siteContainmentProblemsSteps(plan, index, record, ops = newOps()) {
    const /** @type {string[]} */ out = [];
    const gateCells = new Set();
    for (const gate of /** @type {any[]} */ (record?.gates ?? [])) {
        const at = /** @type {any} */ (gate).at ?? {};
        const reach = Math.max(2, Number(gate.width ?? 5)) + 2;
        for (let dx = -reach; dx <= reach; dx += 1) {
            for (let dz = -reach; dz <= reach; dz += 1) {
                gateCells.add(`${String(Number(at.x ?? 0) + dx)},${String(Number(at.z ?? 0) + dz)}`);
            }
        }
    }
    for (const stage of ["lots", "dressing"]) {
        const list = /** @type {any[]} */ (record?.[stage] ?? []);
        for (let i = 0; i < list.length; i += 1) {
            const element = list[i];
            if (BOUNDARY_KINDS.has(String(element.kind))) continue;
            const stray = [];
            yield* pace(ops, Math.min(23000, Number(element.total) * 20 + 100));
            for (const op of siteOpsFor(record, stage, i)) {
                if (!mine(plan, op.x, op.z, index)) stray.push(`${String(op.x)},${String(op.z)}`);
            }
            if (stray.length > 0) {
                out.push(`${stage}/${element.id}: ${String(stray.length)} cells fall outside district ${String(index)} (first: ${stray.slice(0, 3).join(" ")})`);
            }
        }
    }
    const roads = /** @type {any[]} */ (record?.roads ?? []);
    for (let i = 0; i < roads.length; i += 1) {
        const element = roads[i];
        const isLink = String(element.kind) === "road-link" || Number(element.district) !== index;
        const outside = [];
        yield* pace(ops, Math.min(23000, Number(element.total) * 20 + 100));
        for (const op of siteOpsFor(record, "roads", i)) {
            if (!mine(plan, op.x, op.z, index) && !gateCells.has(`${String(op.x)},${String(op.z)}`)) outside.push(op);
        }
        if (!isLink) {
            if (outside.length > 0) {
                out.push(`roads/${element.id}: ${String(outside.length)} cells leave district ${String(index)} without being an approved link (first: ${String(outside[0].x)},${String(outside[0].z)})`);
            }
            continue;
        }
        if (outside.length > 0) {
            const targets = new Set(outside.map((op) => Number(planLabelAt(plan, op.x, op.z))));
            const districts = [...targets].filter((label) => label > 0);
            if (districts.length > 1) out.push(`roads/${element.id}: a link may join one paired district, this one enters ${districts.join(", ")}`);
            if (element.throughGate !== true) out.push(`roads/${element.id}: leaves the district but passes no gate`);
        }
    }
    return out;
}

/**
 * @param {any} plan @param {number} x @param {number} z @param {number} index
 */
function mine(plan, x, z, index) {
    return Number(planLabelAt(plan, x, z)) === index;
}

/**
 * Total ops the plan will emit, from the stored element totals (no regeneration).
 * @param {any} record
 */
export function siteOpCount(record) {
    return STAGES.reduce((sum, stage) => sum + /** @type {any[]} */ (record?.[stage] ?? []).reduce((inner, element) => inner + Number(element.total), 0), 0);
}

