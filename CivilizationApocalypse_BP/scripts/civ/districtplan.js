/**
 * @param {any} clipped a clipField() view
 * @param {{ x0: number, z0: number, x1: number, z1: number }} region
 * @param {Ops} ops
 */
function* snapshotGroundSteps(clipped, region, ops) {
    const w = region.x1 - region.x0 + 1;
    const h = region.z1 - region.z0 + 1;
    const g = new Int16Array(w * h);
    const k = new Uint8Array(w * h);
    const t = new Uint8Array(w * h);
    for (let z = 0; z < h; z += 1) {
        yield* pace(ops, w * 8);
        for (let x = 0; x < w; x += 1) {
            const cell = clipped.at(region.x0 + x, region.z0 + z);
            const code = /** @type {Record<string, number>} */ (KC)[cell.k] ?? 0;
            const i = z * w + x;
            k[i] = code;
            g[i] = code === 0 ? 0 : cell.g;
            t[i] = cell.tree === true ? 1 : 0;
        }
    }
    /** @param {number} x @param {number} z */
    const idx = (x, z) => (x < region.x0 || x > region.x1 || z < region.z0 || z > region.z1 ? -1 : (Math.floor(z) - region.z0) * w + (Math.floor(x) - region.x0));
    return {
        region,
        w,
        h,
        g,
        k,
        t,
        idx,
        /** @param {number} x @param {number} z @returns {number | undefined} */
        ground(x, z) {
            const i = idx(x, z);
            return i < 0 || k[i] === 0 ? undefined : g[i];
        },
        /** @param {number} x @param {number} z @returns {{ g: number, water?: number, hollow?: boolean }} */
        sampler(x, z) {
            const i = idx(x, z);
            if (i < 0 || k[i] === 0) return { g: 0, hollow: true };
            /** @type {{ g: number, water?: number, hollow?: boolean }} */
            const out = { g: /** @type {number} */ (g[i]), hollow: false };
            if (k[i] === KC.water) out.water = out.g + 1;
            return out;
        },
        /** @param {number} x @param {number} z */
        vegetated(x, z) {
            const i = idx(x, z);
            return i >= 0 && k[i] !== 0 && t[i] === 1;
        },
        /** @param {number} x @param {number} z */
        unusable(x, z) {
            const i = idx(x, z);
            return i < 0 || k[i] === 0 || k[i] === KC.lava;
        },
        /** land only: where a building, pad or path may stand @param {number} x @param {number} z */
        isLand(x, z) {
            const i = idx(x, z);
            return i >= 0 && k[i] === KC.land;
        },
    };
}

/**
 * @param {number} x0 @param {number} z0 @param {number} x1 @param {number} z1
 * @param {(x: number, z: number) => { g: number, water?: number, hollow?: boolean }} sampler
 */
function makeRectProfile(x0, z0, x1, z1, sampler) {
    /** @type {import("./foundations.js").Profile} */
    const profile = { x0, z0, w: x1 - x0 + 1, h: z1 - z0 + 1, g: [], water: [], hollow: [] };
    for (let z = z0; z <= z1; z += 1) {
        for (let x = x0; x <= x1; x += 1) {
            const sample = sampler(x, z);
            profile.g.push(sample.g);
            profile.water.push(sample.water);
            profile.hollow.push(sample.hollow === true);
        }
    }
    return profile;
}

/**
 * @param {any} plan
 * @param {number} index
 * @param {string[]} problems
 */
function inputProblems(plan, index, problems) {
    if (plan === null || typeof plan !== "object") {
        problems.push("plan must be a CivPlan object");
        return false;
    }
    if (plan.version !== 1) {
        problems.push(`unsupported CivPlan version ${String(plan.version)}`);
        return false;
    }
    if (!Number.isInteger(index) || index < 1 || index > 5) {
        problems.push(`district index must be 1..5, got ${String(index)}`);
        return false;
    }
    if (!Array.isArray(plan.districts) || !/** @type {any[]} */ (plan.districts).some((district) => district?.index === index)) {
        problems.push(`the plan has no district ${String(index)}`);
        return false;
    }
    if (!Array.isArray(plan.walls) || plan.walls.length === 0) {
        problems.push("the plan has no walls");
        return false;
    }
    return true;
}

/**
 * Ring neighbours in the simulation are 1-2-3-4-5-1.
 * @param {number} a @param {number} b
 */
function isRingPair(a, b) {
    if (a < 1 || b < 1 || a === b) return false;
    const d = Math.abs(a - b);
    return d === 1 || d === 4;
}

